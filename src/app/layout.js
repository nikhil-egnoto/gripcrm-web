import { Space_Grotesk, Inter, Geist } from "next/font/google";
import "./globals.css";
import Header from "@/components/layout/Header";
import Footer from "@/components/layout/Footer";
import { AuthProvider } from "@/context/AuthContext";
import AuthGuard from "@/components/auth/AuthGuard";

const spaceGrotesk = Space_Grotesk({
  variable: "--font-space-grotesk",
  subsets: ["latin"],
});

const inter = Inter({
  variable: "--font-inter",
  subsets: ["latin"],
});

const geist = Geist({
  variable: "--font-geist",
  subsets: ["latin"],
});


export const metadata = {
  title: "Create Next App",
  description: "Generated by create next app",
};

import { GripDataProvider } from "@/context/GripDataContext";
import { fetchAllGripCrmData } from "@/lib/api";
import SmoothScrollProvider from "@/components/providers/SmoothScrollProvider";
import PageFadeTransition from "@/components/providers/PageFadeTransition";
import ToastProvider from "@/components/providers/ToastProvider";

export default async function RootLayout({ children }) {
  const initialData = await fetchAllGripCrmData();

  return (
    <html lang="en">
      <body
        className={`${spaceGrotesk.variable} ${inter.variable} ${geist.variable} antialiased`}
      >
        <ToastProvider />
        <AuthProvider>
          <GripDataProvider initialData={initialData}>
            <AuthGuard>
              <SmoothScrollProvider>
                <Header />
                <PageFadeTransition>
                  {children}
                </PageFadeTransition>
                <Footer />
              </SmoothScrollProvider>
            </AuthGuard>
          </GripDataProvider>
        </AuthProvider>
      </body>
    </html>
  );
}

